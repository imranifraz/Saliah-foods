export function getBlogPostPath(slug) {
  return `/blog/${slug}`;
}

export function getBlogPost(slug) {
  return blogPosts.find((post) => post.id === slug) ?? null;
}

export function getFeaturedPost() {
  return blogPosts.find((post) => post.featured) ?? blogPosts[0];
}

export function getRelatedPosts(slug, limit = 3) {
  const current = getBlogPost(slug);
  if (!current) return blogPosts.slice(0, limit);
  const same = blogPosts.filter((p) => p.id !== slug && p.category === current.category);
  const rest = blogPosts.filter((p) => p.id !== slug && p.category !== current.category);
  return [...same, ...rest].slice(0, limit);
}
